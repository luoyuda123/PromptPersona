def is_rtl(code: str) -> bool:
    for item in LANGS:
        if item["code"] == code:
            return item["rtl"]
    return False


def lang_label(code: str) -> str:
    for item in LANGS:
        if item["code"] == code:
            return item["label"]
    return code


def t(code: str, key: str, **kwargs) -> str:
    """取界面文案；缺失时回退英文，再回退 key 本身。"""
    table = STRINGS.get(code) or STRINGS["en"]
    text = table.get(key)
    if text is None:
        text = STRINGS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def question(code: str, dim_key: str) -> str:
    """按维度键取当前语言的问题文本。"""
